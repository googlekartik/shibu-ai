"""File generation: PowerPoint, Word, Excel and PDF, from a topic.

The user specifies format, length and style in plain language, e.g.
'Create a PowerPoint about Python with 5 slides' or
'Create an Excel workbook with a sales table and a chart'.
Generated files go to generated/ and are served by /api/download/<file>.
"""
import os
import time
import uuid

from utils.security import sanitize_filename


def _out_path(output_dir: str, title: str, ext: str):
    os.makedirs(output_dir, exist_ok=True)
    filename = f"{sanitize_filename(title)}_{int(time.time())}_{uuid.uuid4().hex[:6]}.{ext}"
    return os.path.join(output_dir, filename), filename


def generate_pptx(topic: str, points, output_dir: str, style: str = "simple"):
    from pptx import Presentation
    from pptx.util import Pt
    prs = Presentation()
    title_slide = prs.slides.add_slide(prs.slide_layouts[0])
    title_slide.shapes.title.text = topic
    title_slide.placeholders[1].text = "Generated by Shibu AI"
    for point in points:
        slide = prs.slides.add_slide(prs.slide_layouts[1])
        slide.shapes.title.text = point[:60]
        slide.placeholders[1].text = point
        for shape in slide.placeholders:
            if shape.has_text_frame:
                for para in shape.text_frame.paragraphs:
                    para.font.size = Pt(18)
    path, filename = _out_path(output_dir, topic, "pptx")
    prs.save(path)
    return path, filename


def generate_docx(title: str, content: str, output_dir: str, style: str = "simple"):
    from docx import Document
    doc = Document()
    doc.add_heading(title, level=0)
    for para in content.split("\n"):
        para = para.strip()
        if para.startswith("## "):
            doc.add_heading(para[3:], level=1)
        elif para:
            doc.add_paragraph(para)
    path, filename = _out_path(output_dir, title, "docx")
    doc.save(path)
    return path, filename


def generate_xlsx(title: str, headers, rows, output_dir: str, with_chart: bool = True, with_formulas: bool = True):
    from openpyxl import Workbook
    from openpyxl.chart import BarChart, Reference
    wb = Workbook()
    ws = wb.active
    ws.title = "Data"
    ws.append(headers)
    for row in rows:
        ws.append(row)
    if with_formulas and rows and len(headers) >= 2:
        # Total row: SUM for each numeric column after the first.
        total_row = ["Total"]
        for col_idx in range(1, len(headers)):
            col_letter = chr(ord("A") + col_idx)
            total_row.append(f"=SUM({col_letter}2:{col_letter}{len(rows) + 1})")
        ws.append(total_row)
    if with_chart and rows:
        chart = BarChart()
        chart.title = title
        data = Reference(ws, min_col=2, min_row=1, max_row=len(rows) + 1)
        cats = Reference(ws, min_col=1, min_row=2, max_row=len(rows) + 1)
        chart.add_data(data, titles_from_data=True)
        chart.set_categories(cats)
        ws.add_chart(chart, f"A{len(rows) + 4}")
    path, filename = _out_path(output_dir, title, "xlsx")
    wb.save(path)
    return path, filename
